// Writes src/data.ts from ../data so the package needs no JSON import support.
import fs from "node:fs";
const read = (f) => fs.readFileSync(new URL(`../data/${f}`, import.meta.url), "utf8").trim();
fs.writeFileSync(new URL("./src/data.ts", import.meta.url),
  `// Generated by gen-data.mjs from data/. Do not edit.\n` +
  `export const countriesData: unknown = ${read("countries.json")};\n` +
  `export const provincesData: unknown = ${read("provinces.json")};\n` +
  `export const languagesData: unknown = ${read("languages.json")};\n`);
